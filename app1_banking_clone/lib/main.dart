// HSBC-style banking prototype (App 1).
//
// Purpose: a realistic-looking banking app whose ONLY job is to emit real GA4
// events we legitimately own (login, screen views, transaction funnel) across
// web + Android + iOS from this single codebase. It is a DATA SOURCE for the
// analytics platform (App 2) — not a real bank and never connected to HSBC.
import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';

import 'analytics.dart';
import 'firebase_options.dart';
import 'store.dart';
import 'theme.dart';
import 'screens/login_screen.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  // firebase_options.dart generated by `flutterfire configure`.
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
    await Analytics.appOpen('flutter', 'web');
  } catch (e) {
    // App still runs if Firebase init fails; analytics just no-op.
    // ignore: avoid_print
    print('Firebase init skipped: $e');
  }
  runApp(const HsbcCloneApp());
}

class HsbcCloneApp extends StatefulWidget {
  const HsbcCloneApp({super.key});
  @override
  State<HsbcCloneApp> createState() => _HsbcCloneAppState();
}

class _HsbcCloneAppState extends State<HsbcCloneApp> {
  final AppState _state = AppState();

  @override
  Widget build(BuildContext context) {
    return AppScope(
      state: _state,
      child: MaterialApp(
        title: 'Lumen Bank',
        debugShowCheckedModeBanner: false,
        theme: ThemeData(
          colorScheme: ColorScheme.fromSeed(
            seedColor: hsbcRed,
            primary: hsbcRed,
          ),
          scaffoldBackgroundColor: bgGrey,
          fontFamily: 'Roboto',
          useMaterial3: true,
        ),
        navigatorObservers: [Analytics.observer()],
        home: const LoginScreen(),
      ),
    );
  }
}
