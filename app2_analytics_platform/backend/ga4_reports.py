"""GA4-style report aggregations over the warehouse GA4 tables.

Replicates Google Analytics 4's standard report surface — Overview, Realtime,
Acquisition, Engagement, Retention, Demographics, Tech — using SQL over
hsbc_raw.ga4_sessions (one row per session) and hsbc_raw.ga4_events.

The data is GA4-schema. It is currently generated by our own prototype +
traffic simulator (clearly labelled), and switches to the real GA4 → BigQuery
export automatically once GA4_EXPORT_DATASET is set and ga4_ingest reads it.
"""
from __future__ import annotations

from typing import Any

from bigquery.warehouse import get_warehouse

_wh = None


def wh():
    global _wh
    if _wh is None:
        _wh = get_warehouse()
    return _wh


def _rows(sql: str) -> list[dict[str, Any]]:
    df = wh().query(sql)
    # NaN -> None for JSON safety
    import math
    recs = df.to_dict(orient="records")
    for r in recs:
        for k, v in r.items():
            if isinstance(v, float) and (math.isnan(v) or math.isinf(v)):
                r[k] = None
    return recs


SESS = "hsbc_raw.ga4_sessions"
EVT = "hsbc_raw.ga4_events"


# ---------------------------------------------------------------------------
def overview() -> dict[str, Any]:
    totals = _rows(f"""
        SELECT
          COUNT(*) AS sessions,
          SUM(sessions) AS total_sessions,
          SUM(engaged) AS engaged_sessions,
          SUM(transactions) AS conversions,
          ROUND(SUM(engaged) * 100.0 / COUNT(*), 1) AS engagement_rate,
          ROUND(AVG(engagement_time_sec), 0) AS avg_engagement_sec,
          SUM(CASE WHEN user_type='new' THEN 1 ELSE 0 END) AS new_users,
          SUM(CASE WHEN user_type='returning' THEN 1 ELSE 0 END) AS returning_users
        FROM {SESS}""")[0]
    trend = _rows(f"""
        SELECT session_date AS date,
               COUNT(*) AS sessions,
               SUM(engaged) AS engaged_sessions,
               SUM(transactions) AS conversions
        FROM {SESS} GROUP BY session_date ORDER BY session_date""")
    return {"report": "Overview", "kpis": totals, "trend": trend}


def realtime() -> dict[str, Any]:
    # Treat the most recent day as the "now" slice (sim has daily grain).
    recent = _rows(f"""
        SELECT COUNT(*) AS active_users, SUM(transactions) AS conversions
        FROM {SESS}
        WHERE session_date = (SELECT MAX(session_date) FROM {SESS})""")[0]
    by_country = _rows(f"""
        SELECT country, COUNT(*) AS active_users FROM {SESS}
        WHERE session_date = (SELECT MAX(session_date) FROM {SESS})
        GROUP BY country ORDER BY active_users DESC""")
    by_device = _rows(f"""
        SELECT device_category, COUNT(*) AS active_users FROM {SESS}
        WHERE session_date = (SELECT MAX(session_date) FROM {SESS})
        GROUP BY device_category ORDER BY active_users DESC""")
    top_events = _rows(f"""
        SELECT event_name, SUM(event_count) AS events FROM {EVT}
        WHERE event_date = (SELECT MAX(event_date) FROM {EVT})
        GROUP BY event_name ORDER BY events DESC LIMIT 10""")
    return {"report": "Realtime", "kpis": recent, "by_country": by_country,
            "by_device": by_device, "top_events": top_events}


def acquisition() -> dict[str, Any]:
    by_channel = _rows(f"""
        SELECT channel,
               COUNT(*) AS sessions,
               SUM(CASE WHEN user_type='new' THEN 1 ELSE 0 END) AS new_users,
               SUM(engaged) AS engaged_sessions,
               SUM(transactions) AS conversions,
               ROUND(SUM(engaged)*100.0/COUNT(*),1) AS engagement_rate
        FROM {SESS} GROUP BY channel ORDER BY sessions DESC""")
    by_source = _rows(f"""
        SELECT source, COUNT(*) AS sessions, SUM(transactions) AS conversions
        FROM {SESS} GROUP BY source ORDER BY sessions DESC""")
    return {"report": "Acquisition", "by_channel": by_channel,
            "by_source": by_source}


def engagement() -> dict[str, Any]:
    events = _rows(f"""
        SELECT event_name, SUM(event_count) AS event_count
        FROM {EVT} GROUP BY event_name ORDER BY event_count DESC""")
    kpis = _rows(f"""
        SELECT ROUND(AVG(engagement_time_sec),0) AS avg_engagement_sec,
               SUM(engaged) AS engaged_sessions,
               ROUND(SUM(engaged)*1.0/COUNT(DISTINCT session_date),0) AS engaged_per_day,
               COUNT(*) AS sessions
        FROM {SESS}""")[0]
    trend = _rows(f"""
        SELECT event_date AS date, SUM(event_count) AS events
        FROM {EVT} GROUP BY event_date ORDER BY event_date""")
    return {"report": "Engagement", "kpis": kpis, "events": events, "trend": trend}


def retention() -> dict[str, Any]:
    # Weekly cohort matrix: cohort week (first_seen) x weeks since, % still active.
    matrix = _rows(f"""
        WITH base AS (
          SELECT
            DATE_TRUNC(DATE(first_seen_date), WEEK) AS cohort_week,
            DATE_DIFF(DATE(session_date), DATE(first_seen_date), WEEK) AS weeks_since,
            CONCAT(country, first_seen_date, CAST(engagement_time_sec AS STRING)) AS u
          FROM {SESS}
        )
        SELECT CAST(cohort_week AS STRING) AS cohort,
               weeks_since,
               COUNT(*) AS active
        FROM base
        WHERE weeks_since >= 0 AND weeks_since <= 6
        GROUP BY cohort, weeks_since
        ORDER BY cohort, weeks_since""")
    new_vs_ret = _rows(f"""
        SELECT session_date AS date,
               SUM(CASE WHEN user_type='new' THEN 1 ELSE 0 END) AS new_users,
               SUM(CASE WHEN user_type='returning' THEN 1 ELSE 0 END) AS returning_users
        FROM {SESS} GROUP BY session_date ORDER BY session_date""")
    return {"report": "Retention", "cohort": matrix, "new_vs_returning": new_vs_ret}


def demographics() -> dict[str, Any]:
    country = _rows(f"""
        SELECT country, COUNT(*) AS users, SUM(transactions) AS conversions
        FROM {SESS} GROUP BY country ORDER BY users DESC""")
    age = _rows(f"""
        SELECT age_band, COUNT(*) AS users FROM {SESS}
        GROUP BY age_band ORDER BY age_band""")
    gender = _rows(f"""
        SELECT gender, COUNT(*) AS users FROM {SESS}
        GROUP BY gender ORDER BY users DESC""")
    return {"report": "Demographics", "country": country, "age": age,
            "gender": gender}


def tech() -> dict[str, Any]:
    device = _rows(f"""
        SELECT device_category, COUNT(*) AS users FROM {SESS}
        GROUP BY device_category ORDER BY users DESC""")
    browser = _rows(f"""
        SELECT browser, COUNT(*) AS users FROM {SESS}
        GROUP BY browser ORDER BY users DESC""")
    os_ = _rows(f"""
        SELECT operating_system, COUNT(*) AS users FROM {SESS}
        GROUP BY operating_system ORDER BY users DESC""")
    return {"report": "Tech", "device": device, "browser": browser,
            "operating_system": os_}


REPORTS = {
    "overview": overview, "realtime": realtime, "acquisition": acquisition,
    "engagement": engagement, "retention": retention,
    "demographics": demographics, "tech": tech,
}


def run(report: str) -> dict[str, Any]:
    fn = REPORTS.get(report)
    if not fn:
        return {"error": f"unknown GA4 report '{report}'"}
    try:
        out = fn()
        out["source"] = "Live GA4 \u2192 BigQuery export (analytics_557315782)"
        return out
    except Exception as exc:
        return {"report": report, "error": str(exc)}
